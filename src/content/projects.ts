const ratio = (width: number, height: number) => width / height
/** Full-width image in the 1200px column, cropped to the given Figma height. */
const full = (src: string, height: number, extra: Partial<MediaItem> = {}): MediaItem => ({ src, ratio: ratio(1200, height), ...extra })
/** One of two side-by-side images (586px each at 1512, 28px gap), cropped to the given height. */
const half = (src: string, height: number, extra: Partial<MediaItem> = {}): MediaItem => ({ src, ratio: ratio(586, height), ...extra })

