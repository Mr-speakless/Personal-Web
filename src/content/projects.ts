import { media } from './media'

/** A cropped image: `ratio` is the Figma frame's width / height, applied with object-fit: cover. */
export type MediaItem = { src: string; ratio: number; radius?: number; href?: string; alt?: string; bg?: string; fit?: 'contain' }

export type RichText = string | { before: string; label: string; href: string; after?: string }

/**
 * Detail-page content blocks, listed in the same order as the Figma frame.
 * - heading: JG Heading (40px top gap, rule, 56px text)
 * - paragraphs: 28px body copy in the 1200px column, paragraphs 28px apart
 * - note: 44px remark in the column (e.g. "/The Following Images are all generated by AI.")
 * - video: 16:9 YouTube embed in the column
 * - media: one row of cropped images (one item = full width, two = pair), 28px gap
 * - columns: side-by-side stacks of cropped images; `widths` are fractions of the column, `justify`
 *   centers the group when it is narrower than the column (JingDong composite)
 */
export type Block =
  | { kind: 'heading'; text: string }
  | { kind: 'paragraphs'; text: RichText[] }
  | { kind: 'note'; text: string }
  | { kind: 'video'; id: string; title: string }
  /** Generic iframe embed (e.g. LinkedIn post); `ratio` is the Figma box width / height. */
  | { kind: 'embed'; src: string; title: string; ratio: number }
  | { kind: 'media'; items: MediaItem[]; topGap?: number }
  | { kind: 'columns'; columns: MediaItem[][]; widths?: number[]; gap?: number; rowGap?: number; justify?: 'center' }

export type Project = {
  slug: string
  path: string
  title: string
  cardTitle: string
  cardType: string
  cardSector: string
  cardDate: string
  /** Card default image; `cardHover` is shown on hover and falls back to `cover` (the detail page cover). */
  cardImage: string
  cardHover?: string
  cover: string
  symbol: string
  intro: string
  introLink?: { label: string; href: string }
  /** Optional link on the cover title (COVID19 links to the live dashboard). */
  titleHref?: string
  /** Cover crop; Figma uses contain for Eureka, cover elsewhere. */
  coverFit?: 'contain'
  specifications: readonly [string, string][]
  blocks: Block[]
}

